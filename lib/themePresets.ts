export function getThemePresetById(id: string): ThemePreset | undefined {
  return PREDEFINED_THEMES.find((t) => t.id === id || t.slug === id);
}

export function getDefaultTheme(): ThemePreset {
  return PREDEFINED_THEMES[0]; // Midnight Blue or Dark Crimson
}

export function applyThemeColorsToCss(colors: ThemeColors) {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  root.style.setProperty('--primary-color', colors.primary);
  root.style.setProperty('--secondary-color', colors.secondary);
  root.style.setProperty('--accent-color', colors.accent);
  root.style.setProperty('--background-color', colors.background);
  root.style.setProperty('--surface-color', colors.surface || colors.card);
  root.style.setProperty('--card-color', colors.card);
  root.style.setProperty('--header-color', colors.header);
  root.style.setProperty('--footer-color', colors.footer || colors.background);
  root.style.setProperty('--text-color', colors.text);
  root.style.setProperty('--muted-text-color', colors.mutedText || '#94A3B8');
  root.style.setProperty('--border-color', colors.border || '#27272A');
  root.style.setProperty('--button-color', colors.button || colors.primary);
  root.style.setProperty('--button-text-color', colors.buttonText || '#FFFFFF');
  root.style.setProperty('--active-nav-color', colors.activeNav || colors.primary);
  root.style.setProperty('--hover-color', colors.hover || colors.primary);
}
